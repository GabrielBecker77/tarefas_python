
#Criar um algoritmo que calcule e mostre a área de um triângulo ((base x altura)/2).  Os valores da base e da altura devem ser informados pelo usuário.
print ("Por favor, informe o valor da base do triangulo.")
base = float(input())
print ("Por favor, informe o valor da altura do triangulo.")
altura = float(input())


area = (base * altura) / 2

print (f"A area total do triangulo é de {area:.2f} metros quadrados")