#Elabore um algoritmo que leia uma temperatura em graus centígrados e apresente-a convertida em graus Fahrenheit. A fórmula de conversão é:
#F é a temperatura em Fahrenheit e C é a temperatura em graus centígrados ou Celsius.

print ("Olá! Por favor, informe a temperatura a ser convertida de C para F.")
C = (float(input()) + 32)
X = 9/5
F = (X + C)

print ("A temperatura em graus Fahrenheit será de:",F)
